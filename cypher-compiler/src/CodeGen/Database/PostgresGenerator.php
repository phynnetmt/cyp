<?php

namespace Cypher\Compiler\CodeGen\Database;

use Cypher\Compiler\AST\{
    ModuleNode, ModelDeclStmt, ModelField, ModelRelationship,
};

class PostgresGenerator
{
    private array $generatedFiles = [];
    private array $config;

    public function __construct(array $config = [])
    {
        $this->config = $config;
    }

    public function generate(ModuleNode $module): array
    {
        $this->generatedFiles = [];

        $this->generatedFiles['database/schema.sql'] = $this->generateSchemaHeader();

        foreach ($module->statements as $stmt) {
            if ($stmt instanceof ModelDeclStmt) {
                $this->generateModelSQL($stmt);
            }
        }

        // Generate seed SQL
        $this->generatedFiles['database/seed.sql'] = '-- Database seed data will be inserted here';

        return $this->generatedFiles;
    }

    private function generateSchemaHeader(): string
    {
        return <<<SQL
-- CYP Generated PostgreSQL Schema
-- Generated at: {$this->timestamp()}

-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

SQL;
    }

    private function generateModelSQL(ModelDeclStmt $stmt): void
    {
        $table = $this->tableName($stmt->name);
        $columns = [];
        $indexes = [];
        $foreignKeys = [];

        $columns[] = '    id UUID PRIMARY KEY DEFAULT uuid_generate_v4()';

        foreach ($stmt->fields as $field) {
            $colDef = $this->columnDefinition($field);
            if ($colDef) {
                $columns[] = $colDef;
            }
            // Add index for unique fields
            if (in_array('unique', $field->attributes)) {
                $indexes[] = "CREATE UNIQUE INDEX idx_{$table}_{$field->name} ON {$table}({$field->name});";
            }
        }

        foreach ($stmt->relationships as $rel) {
            $fkCol = $rel->foreignKey;
            $targetTable = $this->tableName($rel->target);
            $columns[] = "    {$fkCol} UUID NOT NULL";
            $foreignKeys[] = "    FOREIGN KEY ({$fkCol}) REFERENCES {$targetTable}(id) ON DELETE CASCADE";
            $indexes[] = "CREATE INDEX idx_{$table}_{$fkCol} ON {$table}({$fkCol});";
        }

        $columns[] = '    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()';
        $columns[] = '    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()';

        // Enable vector extension for AI features
        $hasVector = false;
        foreach ($stmt->fields as $f) {
            if (strtolower($f->type) === 'vector') { $hasVector = true; break; }
        }
        if ($hasVector) {
            $enableVector = "-- Requires pgvector extension\n-- CREATE EXTENSION IF NOT EXISTS vector;\n\n";
        } else {
            $enableVector = '';
        }

        $sql = $enableVector;
        $sql .= "CREATE TABLE IF NOT EXISTS {$table} (\n";
        $sql .= implode(",\n", $columns);
        if (!empty($foreignKeys)) {
            $sql .= ",\n" . implode(",\n", $foreignKeys);
        }
        $sql .= "\n);\n\n";

        // Add table comment
        $sql .= "COMMENT ON TABLE {$table} IS '{$stmt->name} model generated by CYP';\n\n";

        // Add indexes
        foreach ($indexes as $idx) {
            $sql .= $idx . "\n";
        }
        $sql .= "\n";

        // Append to schema file
        $this->generatedFiles['database/schema.sql'] .= $sql;

        // Generate individual migration SQL
        $timestamp = date('Ymd_His');
        $this->generatedFiles["database/migrations/{$timestamp}_create_{$table}_table.sql"] = $sql;
    }

    private function columnDefinition(ModelField $field): ?string
    {
        $pgType = $this->pgType($field->type);
        $nullable = in_array('nullable', $field->attributes) ? '' : ' NOT NULL';
        $unique = in_array('unique', $field->attributes) ? ' UNIQUE' : '';
        $default = '';

        if (in_array('default', $field->attributes)) {
            $default = " DEFAULT '{$field->name}_default'";
        }

        return "    {$field->name} {$pgType}{$nullable}{$unique}{$default}";
    }

    private function pgType(string $type): string
    {
        return match (strtolower($type)) {
            'int', 'integer', 'bigint' => 'BIGINT',
            'string', 'varchar' => 'VARCHAR(255)',
            'text' => 'TEXT',
            'float', 'double', 'decimal' => 'DOUBLE PRECISION',
            'bool', 'boolean' => 'BOOLEAN',
            'datetime', 'timestamp' => 'TIMESTAMP WITH TIME ZONE',
            'date' => 'DATE',
            'json' => 'JSONB',
            'uuid' => 'UUID',
            'vector' => 'vector(1536)',
            'email' => 'VARCHAR(255)',
            'password' => 'VARCHAR(255)',
            default => 'VARCHAR(255)',
        };
    }

    private function tableName(string $name): string
    {
        return strtolower(preg_replace('/(?<!^)[A-Z]/', '_$0', $name)) . 's';
    }

    private function timestamp(): string
    {
        return date('Y-m-d H:i:s');
    }
}
